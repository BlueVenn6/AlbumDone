export function pickMonthEncouragements(
  locale: string,
  count: number,
  random = Math.random,
): string[] {
  const pool = [...MONTHLY_ENCOURAGEMENTS[normalizeLocale(locale)]];
  for (let index = pool.length - 1; index > 0; index -= 1) {
    const other = Math.floor(random() * (index + 1));
    [pool[index], pool[other]] = [pool[other]!, pool[index]!];
  }
  return Array.from(
    { length: count },
    (_, index) => pool[index % pool.length]!,
  );
}

export function nextMonthEncouragement(
  locale: string,
  current: string,
  random = Math.random,
): string {
  const pool = MONTHLY_ENCOURAGEMENTS[normalizeLocale(locale)].filter(
    (text) => text !== current,
  );
  return pool[Math.floor(random() * pool.length)]!;
}
